#!/usr/bin/env node
// Prints the README's provider table, generated from the provider registry (crawler/providers.mjs and the modules it merges), so the
// documentation cannot drift from the code; crawler/tests/providers-registry.test.mjs fails when the README block is out of date.
//   node scripts/provider_table.mjs           print the block
//   node scripts/provider_table.mjs --write   replace the block between the markers in README.md
// Columns, all read from the code: the provider id (the `provider` value of a companies-file entry), what its detect() recognises
// (the URL patterns in its source, or the host patterns the harvest table lists for it), and whether it has a separate detail fetch
// (fetchDescription) for descriptions the list does not carry.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const README_BEGIN = '<!-- provider-table:begin (generated by scripts/provider_table.mjs; do not edit by hand) -->';
export const README_END = '<!-- provider-table:end -->';

const SECTIONS = [
  ['providers.mjs', 'Applicant-tracking systems and career sites', 'crawler/providers.mjs'],
  ['providers-extra.mjs', 'Further ATS families (ported approaches, see NOTICE.md)', 'crawler/providers-extra.mjs'],
  ['providers-research.mjs', 'Research-organisation portals', 'crawler/providers-research.mjs'],
  ['providers-generic.mjs', 'Config-driven readers for sites without an ATS', 'crawler/providers-generic.mjs'],
  ['providers-usajobs.mjs', 'Public-sector source (API key from the environment)', 'crawler/providers-usajobs.mjs'],
  ['providers-eures.mjs', 'Aggregator (unofficial backend, attribution kept)', 'crawler/providers-eures.mjs'],
];

/** What detect() recognises, from its source: the URL regexes it tests, simplified for reading; a constant id marks one employer. */
function recognises(detect, hostPatterns = []) {
  const s = String(detect);
  const fromHosts = hostPatterns.map((re) => re.source);
  const res = fromHosts.length ? fromHosts : [...s.matchAll(/\/((?:\\\/|[^/\n])+?)\/[gimsuy]*\.(?:test|exec)\(|match\(\/((?:\\\/|[^/\n])+?)\/[gimsuy]*\)/g)].map((m) => m[1] ?? m[2]);
  const pretty = [...new Set(res.map((r) => r
    .replace(/^\^/, '').replace(/\$$/, '')
    .replace(/\(\?:https\?:\\\/\\\/\)\?|https\?:\\\/\\\/|\(\?:www\\\.\)\?/g, '')
    .replace(/\\\//g, '/').replace(/\\\./g, '.').replace(/\\-/g, '-').replace(/\|/g, ' or ')))]
    .filter((r) => r.length > 2);
  if (!pretty.length) return 'set by the entry (`slug` or `careers_url`)';
  const shown = pretty.slice(0, 2).map((r) => `\`${r.length > 70 ? `${r.slice(0, 67)}...` : r}\``).join(', ');
  return pretty.length > 2 ? `${shown} (+${pretty.length - 2})` : shown;
}

export async function providerTable() {
  const { providers } = await import('../crawler/providers.mjs');
  const { harvestTable } = await import('../crawler/providers-extra.mjs');
  const hostsOf = new Map(harvestTable.map((h) => [h.providerId, h.hostPatterns ?? []]));
  const modules = {
    'providers-extra.mjs': (await import('../crawler/providers-extra.mjs')).extraProviders,
    'providers-research.mjs': (await import('../crawler/providers-research.mjs')).researchProviders,
    'providers-generic.mjs': (await import('../crawler/providers-generic.mjs')).genericProviders,
  };
  const home = (id) => {
    if (id === 'usajobs') return 'providers-usajobs.mjs';
    if (id === 'eures') return 'providers-eures.mjs';
    for (const [m, set] of Object.entries(modules)) if (set[id] && providers[id] === set[id]) return m;
    return 'providers.mjs';
  };
  const ids = Object.keys(providers);
  const bySection = new Map(SECTIONS.map(([m]) => [m, []]));
  for (const id of ids) bySection.get(home(id)).push(id);
  const out = [];
  out.push(`${ids.length} providers in ${SECTIONS.length} modules. The \`provider\` value of a companies-file entry is the id below; without one, the`);
  out.push('first provider whose detect() recognises the entry\'s `careers_url` is used (registry order).');
  out.push('');
  out.push('| module | what it covers | providers |');
  out.push('|---|---|---:|');
  for (const [m, label, path] of SECTIONS) out.push(`| [\`${m}\`](${path}) | ${label} | ${bySection.get(m).length} |`);
  for (const [m, label] of SECTIONS) {
    const list = bySection.get(m);
    out.push('');
    out.push(`<details><summary><b>${label}</b> (<code>${m}</code>, ${list.length})</summary>`);
    out.push('');
    out.push('| provider | recognises (from its detect()) | detail fetch |');
    out.push('|---|---|:---:|');
    for (const id of list) {
      const p = providers[id];
      out.push(`| \`${id}\` | ${recognises(p.detect, hostsOf.get(id)).replace(/\|/g, '\\|')} | ${typeof p.fetchDescription === 'function' ? 'yes' : ''} |`);
    }
    out.push('');
    out.push('</details>');
  }
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const table = await providerTable();
  if (process.argv.includes('--write')) {
    const path = fileURLToPath(new URL('../README.md', import.meta.url));
    const raw = readFileSync(path, 'utf8');
    const eol = raw.includes('\r\n') ? '\r\n' : '\n';
    const text = raw.replace(/\r\n/g, '\n');
    const a = text.indexOf(README_BEGIN), b = text.indexOf(README_END);
    if (a < 0 || b < a) { console.error('README.md has no provider-table markers'); process.exit(1); }
    const next = `${text.slice(0, a + README_BEGIN.length)}\n${table}\n${text.slice(b)}`;
    writeFileSync(path, next.replace(/\n/g, eol));
    console.log(`README.md provider table written (${table.split('\n').length} lines)`);
  } else {
    console.log(table);
  }
}
